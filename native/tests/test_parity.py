def app_source() -> str:
    """Every line of the application: Python behaviour plus QML presentation."""
    parts = []
    for pattern in ("**/*.py", "**/*.qml"):
        for path in sorted(APP_ROOT.glob(pattern)):
            parts.append(path.read_text(encoding="utf-8"))
    return "\\n".join(parts)


